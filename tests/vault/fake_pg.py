"""In-memory PostgreSQL double for vault target tests.

Interprets only the statement shapes generated by vault targets:

- ``SELECT cols FROM t [WHERE pk > $1] ORDER BY pk LIMIT $n``
- ``UPDATE t SET col = $n | NOW() | COALESCE(col, NOW()) | true | false, ... WHERE pk = $n``
- ``INSERT INTO t (cols) VALUES ($n | 'literal', ...)``

Transactions snapshot the tables and restore them on rollback. ``FakePool``
enforces ``max_size`` so tests catch code that holds a connection while
acquiring another one. ``AsyncdbPool`` wraps any of these pools the way an
asyncdb pool wraps asyncpg: it hands out ``AsyncdbDriver`` objects whose
``execute()`` never raises and whose ``transaction()`` is an awaitable.
"""
import copy
import re
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from typing import Any

_SELECT = re.compile(
    r"^SELECT (?P<cols>.+?) FROM (?P<table>\S+)(?: WHERE (?P<wcol>\S+) > \$1)?"
    r" ORDER BY (?P<ocol>\S+) LIMIT \$(?P<lim>\d+)$"
)
_UPDATE = re.compile(r"^UPDATE (?P<table>\S+) SET (?P<assign>.+) WHERE (?P<pk>\S+) = \$(?P<n>\d+)$")
_ASSIGN = re.compile(
    r"(\w+) = (\$\d+|NOW\(\)|true|false|COALESCE\((\w+), NOW\(\)\))", re.IGNORECASE
)
_INSERT = re.compile(r"^INSERT INTO (?P<table>\S+) \((?P<cols>[^)]+)\) VALUES \((?P<vals>.+)\)$")


def _normalize(sql: str) -> str:
    return " ".join(sql.replace('"', "").split())


class FakeDatabase:
    """Tables are lists of dict rows keyed by fully-qualified table name."""

    def __init__(self) -> None:
        self.tables: dict[str, list[dict[str, Any]]] = {}
        self.statements: list[str] = []

    def table(self, name: str) -> list[dict[str, Any]]:
        return self.tables.setdefault(name, [])

    def now(self) -> datetime:
        return datetime.now(timezone.utc)


class FakeTransaction:
    def __init__(self, db: FakeDatabase) -> None:
        self._db = db
        self._snapshot: dict[str, list[dict[str, Any]]] = {}

    async def start(self) -> None:
        self._snapshot = copy.deepcopy(self._db.tables)

    async def commit(self) -> None:
        self._snapshot = {}

    async def rollback(self) -> None:
        self._db.tables = self._snapshot


class FakeConnection:
    def __init__(self, db: FakeDatabase) -> None:
        self._db = db

    def transaction(self) -> FakeTransaction:
        return FakeTransaction(self._db)

    async def fetch(self, sql: str, *args: Any) -> list[dict[str, Any]]:
        stmt = _normalize(sql)
        self._db.statements.append(stmt)
        match = _SELECT.match(stmt)
        if not match:
            raise AssertionError(f"FakeConnection cannot interpret: {stmt}")
        cols = [c.strip() for c in match["cols"].split(",")]
        rows = sorted(self._db.table(match["table"]), key=lambda r: r[match["ocol"]])
        if match["wcol"]:
            rows = [r for r in rows if r[match["wcol"]] > args[0]]
        limit = args[int(match["lim"]) - 1]
        return [{c: row[c] for c in cols} for row in rows[:limit]]

    async def execute(self, sql: str, *args: Any) -> str:
        stmt = _normalize(sql)
        self._db.statements.append(stmt)
        if match := _UPDATE.match(stmt):
            pk_value = args[int(match["n"]) - 1]
            count = 0
            for row in self._db.table(match["table"]):
                if row[match["pk"]] != pk_value:
                    continue
                for column, expr, coalesce_col in _ASSIGN.findall(match["assign"]):
                    if expr.startswith("$"):
                        row[column] = args[int(expr[1:]) - 1]
                    elif expr == "NOW()":
                        row[column] = self._db.now()
                    elif expr.lower() in ("true", "false"):
                        row[column] = expr.lower() == "true"
                    else:
                        row[column] = row[coalesce_col] or self._db.now()
                count += 1
            return f"UPDATE {count}"
        if match := _INSERT.match(stmt):
            cols = [c.strip() for c in match["cols"].split(",")]
            vals = [v.strip() for v in match["vals"].split(",")]
            row = {}
            for col, val in zip(cols, vals):
                if val.startswith("$"):
                    row[col] = args[int(val[1:]) - 1]
                elif val.upper() == "NULL":
                    row[col] = None
                else:
                    row[col] = val.strip("'")
            self._db.table(match["table"]).append(row)
            return "INSERT 0 1"
        raise AssertionError(f"FakeConnection cannot interpret: {stmt}")


class FakePool:
    """asyncpg-style pool: ``acquire()`` is an async context manager."""

    def __init__(self, db: FakeDatabase, max_size: int = 1) -> None:
        self.db = db
        self.max_size = max_size
        self.in_use = 0

    @asynccontextmanager
    async def _acquire(self):
        if self.in_use >= self.max_size:
            raise RuntimeError("FakePool exhausted (connection held while acquiring another)")
        self.in_use += 1
        try:
            yield FakeConnection(self.db)
        finally:
            self.in_use -= 1

    def acquire(self):
        return self._acquire()


class AwaitablePool:
    """asyncdb-style pool: ``await acquire()`` then ``release(conn)``."""

    def __init__(self, db: FakeDatabase) -> None:
        self.db = db
        self.released = 0

    async def acquire(self) -> FakeConnection:
        return FakeConnection(self.db)

    async def release(self, conn: FakeConnection) -> None:
        self.released += 1


class AsyncdbDriver:
    """asyncdb ``pg`` driver double (asyncdb 2.16 semantics) around a native connection.

    ``engine()`` returns the native connection; ``transaction()`` is an awaitable
    that starts the transaction and returns the driver; ``execute()`` swallows
    every error and returns ``[result, error]``; ``fetch_all()`` returns ``None``
    when there are no rows.
    """

    def __init__(self, raw: Any) -> None:
        self._raw = raw
        self._tx: Any = None
        self._cm: Any = None

    def engine(self) -> Any:
        return self._raw

    async def transaction(self) -> "AsyncdbDriver":
        self._tx = self._raw.transaction()
        await self._tx.start()
        return self

    async def commit(self) -> None:
        if self._tx is not None:
            await self._tx.commit()
            self._tx = None

    async def rollback(self) -> None:
        if self._tx is not None:
            await self._tx.rollback()
            self._tx = None

    async def execute(self, sql: str, *args: Any) -> list[Any]:
        try:
            return [await self._raw.execute(sql, *args), None]
        except Exception as err:  # noqa: BLE001 - mirrors asyncdb, which never raises here
            return [None, err]

    async def fetch_all(self, sql: str, *args: Any) -> Any:
        rows = await self._raw.fetch(sql, *args)
        return rows or None


class AsyncdbPool:
    """asyncdb-style pool double wrapping an asyncpg-style pool.

    ``acquire()`` is an async context manager (asyncdb >= 2.x) or, with
    ``awaitable=True``, a coroutine followed by ``release(driver)``.
    """

    def __init__(self, inner: Any, *, awaitable: bool = False) -> None:
        self.inner = inner
        self.awaitable = awaitable
        self.released = 0

    def acquire(self):
        if self.awaitable:
            return self._acquire_driver()
        return self._context()

    @asynccontextmanager
    async def _context(self):
        try:
            async with self.inner.acquire() as raw:
                yield AsyncdbDriver(raw)
        finally:
            self.released += 1

    async def _acquire_driver(self) -> AsyncdbDriver:
        cm = self.inner.acquire()
        driver = AsyncdbDriver(await cm.__aenter__())
        driver._cm = cm
        return driver

    async def release(self, driver: AsyncdbDriver) -> None:
        self.released += 1
        await driver._cm.__aexit__(None, None, None)
